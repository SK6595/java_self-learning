public class Main16 {
  public static void main(String[] args) {
    System.out.println("メソッドを呼び出します");
    hello();
    System.out.println("メソッドの呼び出しが終わりました");
  }
  // シンプルなメソッド定義.
  // helloメソッドの定義
  public static void hello() {
    // helloメソッドが呼び出された時の処理
    System.out.println("湊さん、こんにちは");
  }
}